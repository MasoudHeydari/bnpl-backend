package middleware

import (
	"errors"
	"net/http"

	"github.com/gin-gonic/gin"

	"github.com/parstis/bnpl-backend/pkg/adapter/restful/gin/serdser"
	"github.com/parstis/bnpl-backend/pkg/core/cerr"
	coreerrorreporting "github.com/parstis/bnpl-backend/pkg/core/errorreporting"
	corelog "github.com/parstis/bnpl-backend/pkg/core/log"
	"github.com/parstis/bnpl-backend/pkg/core/trace"
)

// ErrorHandler centralizes HTTP error handling for errors registered on the
// Gin context via c.Error(err).
//
// Downstream handlers and middleware are responsible only for reporting an
// error and aborting their own flow. ErrorHandler owns the transport-boundary
// concerns that should not be repeated in every handler:
//
//   - classify the application error for HTTP handling;
//   - log server-side failures through the application's Logger abstraction;
//   - serialize the public, sanitized error response through serdser;
//   - avoid writing a second response when downstream code already wrote one.
//
// Client-side errors (4xx) are intentionally not logged here. They are expected
// outcomes of the API contract and logging every validation/not-found failure at
// error level would create noise.
//
// Server-side failures (5xx) are logged together with request tracing
// identifiers so the trace_id returned to the caller can be correlated with
// the actual internal failure.
//
// ErrorHandler must run after TraceID in the middleware registration order so
// trace/request/correlation identifiers are available when an error is logged.
//
// Ordering relative to AccessLogger / HTTPDebugLogger: ErrorHandler is
// registered after those loggers so it executes inside their c.Next() calls.
// While the stack unwinds, ErrorHandler serializes the public error response
// first; the outer loggers then observe the final HTTP status, size, and
// (when capture is enabled) response body bytes. Moving ErrorHandler outside
// AccessLogger would make access logs miss ErrorHandler-written statuses.
func ErrorHandler(
	logger corelog.Logger,
	reporter coreerrorreporting.Reporter,
) gin.HandlerFunc {
	return func(c *gin.Context) {
		// Execute the rest of the middleware/handler chain first.
		//
		// Errors are collected on c.Errors by downstream code and handled here
		// while the middleware stack is unwinding.
		c.Next()

		// Nothing was reported by downstream handlers.
		if len(c.Errors) == 0 {
			return
		}

		// A request can only have one public error response.
		//
		// If multiple errors were registered while processing the request,
		// the latest one is considered the transport-level failure.
		ginErr := c.Errors.Last()
		if ginErr == nil || ginErr.Err == nil {
			return
		}

		err := ginErr.Err

		code, statusCode := classifyHTTPError(err)

		// Only server-side failures are logged here.
		//
		// 4xx errors such as validation failures, not-found responses, and
		// conflicts are part of the normal API contract and should not pollute
		// the error logs.
		if statusCode >= http.StatusInternalServerError {
			logServerError(
				c,
				logger,
				code,
				statusCode,
				err,
			)

			reportServerError(c, reporter, code, statusCode, err)
		}

		// A downstream middleware may have already committed a response.
		//
		// We still log the error above, but must never attempt to write a second
		// response body.
		if c.Writer.Written() {
			return
		}

		// serdser owns only the public HTTP representation of the error.
		//
		// It must never log the internal error and must never expose the
		// underlying cause.
		serdser.SerErr(c, err)
	}
}

// classifyHTTPError determines the error code and HTTP status that belong to
// the REST boundary.
//
// Unknown errors, malformed cerr errors, and unknown application codes fail
// closed as INTERNAL_ERROR. This prevents implementation mistakes or newly
// introduced error codes from accidentally becoming part of the public API
// contract.
func classifyHTTPError(err error) (cerr.Code, int) {
	var appErr *cerr.Error

	// A plain/unclassified Go error is always considered internal.
	if !errors.As(err, &appErr) ||
		appErr == nil ||
		appErr.Code == "" {
		return cerr.CodeInternalError, http.StatusInternalServerError
	}

	statusCode := serdser.StatusCode(appErr.Code)

	// StatusCode maps unknown codes to HTTP 500.
	//
	// Normalize the application code too, so the log and the response both
	// describe the failure consistently as INTERNAL_ERROR.
	if statusCode == http.StatusInternalServerError &&
		appErr.Code != cerr.CodeInternalError {
		return cerr.CodeInternalError, http.StatusInternalServerError
	}

	return appErr.Code, statusCode
}

// logServerError writes the private/internal failure to the application logger.
//
// The caller receives only the sanitized response generated by serdser. The
// underlying err is intentionally logged here so operators can find the real
// cause using the trace_id returned in the API response.
//
// This function depends only on core/log.Logger. It does not know whether the
// concrete implementation is slog, zap, noop, or anything else.
func logServerError(
	c *gin.Context,
	logger corelog.Logger,
	code cerr.Code,
	statusCode int,
	err error,
) {
	ctx := c.Request.Context()

	logger.Error(
		"http request failed with server error",

		"error_code", code,

		"trace_id", trace.ID(ctx),
		"request_id", trace.RequestID(ctx),
		"correlation_id", trace.CorrelationID(ctx),

		"http.method", c.Request.Method,
		"http.path", SanitizeHTTPPathForLog(c.Request.URL.Path),
		"http.route", c.FullPath(),
		"http.status_code", statusCode,

		// err is server-side diagnostic information.
		// It must never be copied into the HTTP response.
		"error", err,
	)
}

// reportServerError reports a 5xx failure once at the HTTP transport boundary.
//
// Only bounded metadata is attached. Request paths, query parameters, headers,
// cookies, and bodies are intentionally excluded from the external event.
func reportServerError(
	c *gin.Context,
	reporter coreerrorreporting.Reporter,
	code cerr.Code,
	statusCode int,
	err error,
) {
	if reporter == nil || err == nil {
		return
	}

	reporter.CaptureError(
		requestContext(c),
		err,
		httpErrorMetadata(c, string(code), statusCode),
	)
}
