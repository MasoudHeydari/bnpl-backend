func TestCollectionsDecisionFingerprint_PostgreSQLAcceptsHashedForm(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()

	pool := openIntegrationPool(t, ctx)

	tx, err := pool.Begin(ctx)
	require.NoError(t, err)
	defer func() { _ = tx.Rollback(ctx) }()

	hasher := sha256fingerprint.New()
	openValue, err := hasher.Hash("collections-default-open:v1:test|" + uuid.NewString())
	require.NoError(t, err)
	require.NoError(t, openValue.Validate())

	recoverValue, err := hasher.Hash("collections-default-recover:v1:test|" + uuid.NewString())
	require.NoError(t, err)
	require.NoError(t, recoverValue.Validate())

	targetID := uuid.New()
	now := time.Now().UTC()

	var openDecisionID uuid.UUID
	err = tx.QueryRow(
		ctx,
		`
INSERT INTO decisions (
	type, target_type, target_id, outcome, reason_codes,
	policy_id, policy_version, jurisdiction, actor_type,
	decided_at, created_at, idempotency_key, idempotency_fingerprint
) VALUES (
	'restriction', 'customer_profile', $1, 'restricted', ARRAY['COLLECTIONS_GRACE_PERIOD_EXCEEDED'],
	'collections_default', 'v1', 'IR', 'system',
	$2, $2, $3, $4
)
RETURNING id`,
		targetID,
		now,
		"collections_default_open:"+uuid.NewString(),
		openValue.String(),
	).Scan(&openDecisionID)
	require.NoError(t, err, "hashed open fingerprint must satisfy decisions CHECK")

	var recoverDecisionID uuid.UUID
	err = tx.QueryRow(
		ctx,
		`
INSERT INTO decisions (
	type, target_type, target_id, outcome, reason_codes,
	policy_id, policy_version, jurisdiction, actor_type,
	prior_decision_id,
	decided_at, created_at, idempotency_key, idempotency_fingerprint
) VALUES (
	'restriction', 'customer_profile', $1, 'unrestricted', ARRAY['COLLECTIONS_DUE_INSTALLMENTS_SETTLED'],
	'collections_default', 'v1', 'IR', 'system',
	$2,
	$3, $3, $4, $5
)
RETURNING id`,
		targetID,
		openDecisionID,
		now,
		"collections_default_recover:"+uuid.NewString(),
		recoverValue.String(),
	).Scan(&recoverDecisionID)
	require.NoError(t, err, "hashed recover fingerprint must satisfy decisions CHECK")

	var prior *uuid.UUID
	err = tx.QueryRow(
		ctx,
		`SELECT prior_decision_id FROM decisions WHERE id = $1`,
		recoverDecisionID,
	).Scan(&prior)
	require.NoError(t, err)
	require.NotNil(t, prior)
	require.Equal(t, openDecisionID, *prior)

	_, err = tx.Exec(
		ctx,
		`
INSERT INTO decisions (
	type, target_type, target_id, outcome, reason_codes,
	policy_id, policy_version, jurisdiction, actor_type,
	decided_at, created_at, idempotency_key, idempotency_fingerprint
) VALUES (
	'restriction', 'customer_profile', $1, 'restricted', ARRAY['COLLECTIONS_GRACE_PERIOD_EXCEEDED'],
	'collections_default', 'v1', 'IR', 'system',
	$2, $2, $3, $4
)`,
		targetID,
		now,
		"collections_default_open_bad:"+uuid.NewString(),
		fmt.Sprintf("collections_default|v1|%s|[]", model.CustomerID(targetID).String()),
	)
	require.Error(t, err, "raw fmt.Sprintf fingerprint must fail decisions CHECK")
}

// openIntegrationPool creates an isolated fixture schema in a disposable
// database. It must not depend on a pre-populated decisions table.
func openIntegrationPool(t *testing.T, ctx context.Context) *pgxpool.Pool {
	t.Helper()

	dsn := strings.TrimSpace(os.Getenv("COLLECTIONS_TEST_DATABASE_URL"))
	if dsn == "" {
		dsn = postgresDSNFromEnv()
	}
	if dsn == "" {
		t.Fatal("disposable PostgreSQL connection is required for decision integration tests")
	}

	cfg, err := pgxpool.ParseConfig(dsn)
	require.NoError(t, err)

	schema := "decision_fingerprint_it_" + strings.ReplaceAll(uuid.NewString(), "-", "")
	cfg.ConnConfig.RuntimeParams["search_path"] = schema
	pool, err := pgxpool.NewWithConfig(ctx, cfg)
	require.NoError(t, err)
	t.Cleanup(func() {
		cleanupCtx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
		defer cancel()

		// This schema name is generated by uuid.NewString, not user input.
		_, _ = pool.Exec(cleanupCtx, "DROP SCHEMA IF EXISTS "+schema+" CASCADE")
		pool.Close()
	})
	require.NoError(t, pool.Ping(ctx))

	_, err = pool.Exec(ctx, "CREATE SCHEMA "+schema)
	require.NoError(t, err)

	ddl, err := os.ReadFile("../migrationsrp/000_schema.sql")
	require.NoError(t, err)

	// Fixtures have independent search paths, including those of trigger
	// functions added for strict credit-owner and account enforcement.
	baseline := strings.SplitN(
		string(ddl),
		"-- MANAGED DATABASE PERMISSIONS: canonical initial grants (pre-release)",
		2,
	)[0]
	baseline = strings.ReplaceAll(baseline, "SET search_path TO bnpl;", "SET search_path TO "+schema+";")
	baseline = strings.ReplaceAll(baseline, "bnpl.", schema+".")
	baseline = strings.ReplaceAll(baseline, "SET search_path = bnpl, pg_temp", "SET search_path = "+schema+", pg_temp")
	baseline = strings.ReplaceAll(baseline, "pg_catalog, bnpl", "pg_catalog, "+schema)
	_, err = pool.Exec(ctx, baseline)
	require.NoError(t, err)

	return pool
}

func postgresDSNFromEnv() string {
	user := strings.TrimSpace(os.Getenv("POSTGRES_USER"))
	password := os.Getenv("POSTGRES_PASSWORD")
	host := strings.TrimSpace(os.Getenv("POSTGRES_HOST"))
	port := strings.TrimSpace(os.Getenv("POSTGRES_PORT"))
	db := strings.TrimSpace(os.Getenv("POSTGRES_DB"))
	sslMode := strings.TrimSpace(os.Getenv("POSTGRES_SSL_MODE"))
	if sslMode == "" {
		sslMode = "disable"
	}

	if user == "" || host == "" || port == "" || db == "" {
		return ""
	}

	return fmt.Sprintf(
		"postgres://%s:%s@%s:%s/%s?sslmode=%s",
		user,
		password,
		host,
		port,
		db,
		sslMode,
	)
}
